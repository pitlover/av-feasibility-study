"""Convert raw-frame manifest to prepared JPEG manifest (virtual images written once)."""
import argparse
from pathlib import Path

import cv2
from datasets import load_manifest, load_virtual_bgr
from build_index import write_json


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--index', required=True)
    p.add_argument('--out-dir', required=True)
    p.add_argument('--manifest', required=True)
    p.add_argument('--jpeg-quality', type=int, default=95)
    p.add_argument('--overwrite', action='store_true')
    args = p.parse_args()
    index = load_manifest(args.index)
    if index['stage'] != 'raw':
        raise ValueError('Expected raw index generated by build_index.py')
    out = Path(args.out_dir)
    for sidx, seq in enumerate(index['sequences']):
        dest = out / seq['split'] / f'seq_{sidx:05d}'
        dest.mkdir(parents=True, exist_ok=True)
        for i, frame in enumerate(seq['frames']):
            target = dest / f'{i:06d}.jpg'
            if args.overwrite or not target.exists():
                img = load_virtual_bgr(seq, frame, mode='online')
                if not cv2.imwrite(str(target), img,
                                   [cv2.IMWRITE_JPEG_QUALITY, args.jpeg_quality]):
                    raise IOError(f'Failed writing {target}')
            frame['prepared_path'] = str(target.resolve())
        print(f"Prepared {seq['name']} ({len(seq['frames'])} images)", flush=True)
    index['stage'] = 'prepared'
    write_json(args.manifest, index)
    print('Saved prepared manifest:', args.manifest)


if __name__ == '__main__':
    main()
